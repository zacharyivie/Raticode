from __future__ import annotations

import importlib.util
import subprocess
import sys
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import pytest

ROOT = Path(__file__).resolve().parents[2]


@pytest.fixture(scope="module")
def checker() -> Iterator[Any]:
    path = ROOT / "scripts/check-commit-messages.py"
    spec = importlib.util.spec_from_file_location("check_commit_messages", path)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    monkeypatch = pytest.MonkeyPatch()
    monkeypatch.setitem(sys.modules, "check_commit_messages", module)
    spec.loader.exec_module(module)
    yield module
    monkeypatch.undo()


def _git(repo: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-c", "user.name=Test", "-c", "user.email=test@example.com", *args],
        cwd=repo,
        capture_output=True,
        text=True,
        check=True,
    ).stdout


def _commit(repo: Path, message: str) -> None:
    _git(repo, "commit", "--allow-empty", "-q", "-m", message)


@pytest.mark.parametrize(
    "line",
    [
        "Co-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>",
        "co-authored-by: Codex <codex@openai.com>",
        "Co-authored-by: Copilot <175728472+Copilot@users.noreply.github.com>",
        "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
        "Generated by Gemini",
    ],
)
def test_lines_crediting_an_ai_tool_are_found(checker: Any, line: str) -> None:
    message = f"fix: Something\n\n - A change\n\n{line}\n"
    assert checker.offending_lines(message) == [line.strip()]


@pytest.mark.parametrize(
    "line",
    [
        "Co-Authored-By: Devin Smith <devin@example.com>",
        "Co-Authored-By: Ana Lopez <ana@example.com>",
        " - Keep Raticode's tool-server tokens off Codex's command line",
        " - Generated reports keep their links",
        "Docs-not-needed: agent instructions only",
    ],
)
def test_people_and_ordinary_lines_pass(checker: Any, line: str) -> None:
    assert checker.offending_lines(f"fix: Something\n\n{line}\n") == []


def test_only_commits_after_the_base_are_read(
    checker: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: Any
) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "dev")
    _commit(repo, "feat: Old work\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    _git(repo, "checkout", "-q", "-b", "topic")
    _commit(repo, "fix: Clean message\n\n - A change")
    monkeypatch.setattr(checker, "ROOT", repo)
    assert checker.main(["--base", "dev"]) == 0
    assert "1 commits checked" in capsys.readouterr().out

    _commit(repo, "fix: Another\n\n - B\n\nCo-Authored-By: Claude <noreply@anthropic.com>")
    assert checker.main(["--base", "dev"]) == 1
    out = capsys.readouterr().out
    assert "Co-Authored-By: Claude <noreply@anthropic.com>" in out
    assert "1 of 2 commits credit an AI tool" in out


def test_an_unknown_base_is_reported(
    checker: Any, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: Any
) -> None:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "dev")
    _commit(repo, "feat: First")
    monkeypatch.setattr(checker, "ROOT", repo)
    assert checker.main(["--base", "no-such-branch"]) == 2
    assert "Couldn't read the commits" in capsys.readouterr().out
